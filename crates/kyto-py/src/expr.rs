//! The Python `CellExpr` and `GeneExpr` (task 3.3), their `str` namespaces, and the
//! expression constructors (task 3.4): `cell_column`, `gene_column`, `gene_expression`,
//! `cell_profile`, `cell_embedding`, `gene_embedding` and `feature`.
//!
//! Does: wrap `kyto_core::CellExpr` / `GeneExpr` in frozen pyclasses with Python
//! operators; convert Python operands (an expression of the same axis, `bool`, `int`,
//! `float`, `str`) and raise `KY-E202` when the other operand is an expression of the
//! other axis (R5), `KY-E212` for `==` / `!=` with `None` (it names the null test to
//! write, task 3.7), `KY-E205` for any other operand kyto does not accept, and `KY-E206`
//! when Python asks for the truth value of an expression.
//! Does not: check dtypes (kyto-core does), resolve names (`Atlas.resolve`, task 3.5),
//! or evaluate.
//! `feature` only parses its name (`KY-E208`), the embedding constructors check their
//! component (`KY-E209`); no constructor checks a name against a schema, since they
//! have none (R7).
//! The two classes are generated by one macro so they cannot drift apart.

use kyto_core::{
    BinaryOp, CellExpr, ExprAxis, ExprDtype, GeneExpr, Literal, NullTest, Operand, StrFunction,
};
use kyto_error::KytoError;
use pyo3::basic::CompareOp;
use pyo3::prelude::*;
use pyo3::types::{PyBool, PyFloat, PyInt, PyString, PyType};

use crate::errors::to_py_err;

/// Longest operand `repr` quoted in a `KY-E205` message, in characters.
const MAX_OPERAND_CHARS: usize = 80;

/// What a binary operation accepts besides an expression of its own axis.
const ACCEPTED_OPERANDS: &str = "an expression of the same axis, or a bool, int, float or str";

/// The `KY-E205` error for an operand that is neither an expression nor a literal.
fn foreign_operand(operation: &str, other: &Bound<'_, PyAny>) -> KytoError {
    let type_name = other
        .get_type()
        .name()
        .map_or_else(|_| "object".to_owned(), |name| name.to_string());
    let text = other
        .repr()
        .map_or_else(|_| format!("<{type_name}>"), |text| text.to_string());
    let operand = if text.chars().count() > MAX_OPERAND_CHARS {
        let short: String = text.chars().take(MAX_OPERAND_CHARS).collect();
        format!("{short}...")
    } else {
        text
    };
    KytoError::ExpressionOperand {
        operation: operation.to_owned(),
        accepted: ACCEPTED_OPERANDS.to_owned(),
        got: format!("a {type_name}"),
        operand,
    }
}

/// A Python literal as a [`Literal`], or `None` if `other` is not one.
fn literal(operation: &str, other: &Bound<'_, PyAny>) -> Result<Option<Literal>, KytoError> {
    // `bool` first: it is a subclass of `int`.
    if let Ok(value) = other.cast::<PyBool>() {
        return Ok(Some(Literal::Boolean(value.is_true())));
    }
    if other.is_instance_of::<PyInt>() {
        return match other.extract::<i64>() {
            Ok(value) => Ok(Some(Literal::Int(value))),
            Err(_) => Err(KytoError::ExpressionOperand {
                operation: operation.to_owned(),
                accepted: "an int between -2**63 and 2**63 - 1".to_owned(),
                got: "an int outside that range".to_owned(),
                operand: other
                    .repr()
                    .map_or_else(|_| "int".to_owned(), |text| text.to_string()),
            }),
        };
    }
    if let Ok(value) = other.cast::<PyFloat>() {
        return Ok(Some(Literal::Float(value.value())));
    }
    if let Ok(value) = other.cast::<PyString>() {
        return Ok(Some(Literal::String(
            value
                .to_str()
                .map_err(|_| foreign_operand(operation, other))?
                .to_owned(),
        )));
    }
    Ok(None)
}

/// The kyto-py class of the expression of the other axis, as a mixing check.
trait MixCheck<A: ExprAxis> {
    /// `KY-E202` if `other` is an expression of the other axis.
    fn mixed(
        operation: &str,
        this: &kyto_core::Expr<A>,
        other: &Bound<'_, PyAny>,
    ) -> Option<KytoError>;
}

/// The `KY-E212` error for `expression == None` or `expression != None`. `None` is not a
/// null literal: the comparison would be null on every row (Polars) or constant
/// (pandas), never a test for missing values. `None == x` reaches here as `x == None`.
fn null_comparison<A: ExprAxis>(operation: &str, expression: &kyto_core::Expr<A>) -> KytoError {
    let test = if operation == "==" {
        NullTest::IsNull
    } else {
        NullTest::IsNotNull
    };
    let suggestion = expression.null_test(test).map_or_else(
        |_| format!("({expression}).{}()", test.name()),
        |tested| tested.to_string(),
    );
    KytoError::NullComparison {
        operation: operation.to_owned(),
        expression: if matches!(**expression.node(), kyto_core::ExprNode::Binary { .. }) {
            format!("({expression}) {operation} None")
        } else {
            format!("{expression} {operation} None")
        },
        suggestion,
    }
}

/// Raise `KY-E206` with `expression` in the message.
fn truth_value<A: ExprAxis>(py: Python<'_>, expression: &kyto_core::Expr<A>) -> PyErr {
    to_py_err(py, &expression.truth_value_error())
}

/// The `kyto.dtypes` marker class for `dtype`.
fn dtype_class(py: Python<'_>, dtype: ExprDtype) -> PyResult<Bound<'_, PyAny>> {
    let name = match dtype {
        ExprDtype::Unknown => "Unknown",
        ExprDtype::Boolean => "Boolean",
        ExprDtype::Numeric => "Numeric",
        ExprDtype::String => "String",
    };
    py.import("kyto.dtypes")?.getattr(name)
}

macro_rules! expr_class {
    (
        $(#[$class_doc:meta])*
        class $class:ident ($name:literal, $axis:ty, $core:ty);
        $(#[$namespace_doc:meta])*
        namespace $namespace:ident ($namespace_name:literal);
    ) => {
        $(#[$class_doc])*
        #[pyclass(frozen, module = "kyto", name = $name)]
        pub struct $class {
            expr: $core,
        }

        impl $class {
            /// The wrapped expression.
            pub(crate) fn core(&self) -> &$core {
                &self.expr
            }

            /// Wrap `expr`.
            pub(crate) fn from_core(expr: $core) -> Self {
                Self { expr }
            }

            fn operand(&self, operation: &str, other: &Bound<'_, PyAny>) -> Result<Operand<$axis>, KytoError> {
                if let Ok(other) = other.cast::<$class>() {
                    return Ok(Operand::Expr(other.get().expr.clone()));
                }
                if let Some(error) = <$class as MixCheck<$axis>>::mixed(operation, &self.expr, other) {
                    return Err(error);
                }
                if other.is_none() && matches!(operation, "==" | "!=") {
                    return Err(null_comparison(operation, &self.expr));
                }
                match literal(operation, other)? {
                    Some(literal) => Ok(Operand::Literal(literal)),
                    None => Err(foreign_operand(operation, other)),
                }
            }

            /// `self.is_null()` or `self.is_not_null()`.
            fn null_test(&self, py: Python<'_>, test: NullTest) -> PyResult<Self> {
                self.expr.null_test(test).map(|expr| Self { expr }).map_err(|error| to_py_err(py, &error))
            }

            /// `self op other`, or `other op self` when `reversed`.
            fn apply(&self, py: Python<'_>, op: BinaryOp, other: &Bound<'_, PyAny>, reversed: bool) -> PyResult<Self> {
                let result = self.operand(op.symbol(), other).and_then(|other| {
                    let this = Operand::Expr(self.expr.clone());
                    if reversed {
                        <$core>::binary(other, op, this)
                    } else {
                        <$core>::binary(this, op, other)
                    }
                });
                result.map(|expr| Self { expr }).map_err(|error| to_py_err(py, &error))
            }
        }

        #[pymethods]
        impl $class {
            /// Compare with ``==``, ``!=``, ``<``, ``<=``, ``>`` or ``>=``: a boolean
            /// expression.
            fn __richcmp__(&self, py: Python<'_>, other: &Bound<'_, PyAny>, op: CompareOp) -> PyResult<Self> {
                let op = match op {
                    CompareOp::Eq => BinaryOp::Eq,
                    CompareOp::Ne => BinaryOp::NotEq,
                    CompareOp::Lt => BinaryOp::Lt,
                    CompareOp::Le => BinaryOp::LtEq,
                    CompareOp::Gt => BinaryOp::Gt,
                    CompareOp::Ge => BinaryOp::GtEq,
                };
                self.apply(py, op, other, false)
            }

            /// ``self + other``.
            fn __add__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Add, other, false)
            }

            /// ``other + self``.
            fn __radd__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Add, other, true)
            }

            /// ``self - other``.
            fn __sub__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Sub, other, false)
            }

            /// ``other - self``.
            fn __rsub__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Sub, other, true)
            }

            /// ``self * other``.
            fn __mul__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Mul, other, false)
            }

            /// ``other * self``.
            fn __rmul__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Mul, other, true)
            }

            /// ``self / other`` (true division).
            fn __truediv__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Div, other, false)
            }

            /// ``other / self`` (true division).
            fn __rtruediv__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Div, other, true)
            }

            /// ``self & other`` (logical and).
            fn __and__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::And, other, false)
            }

            /// ``other & self`` (logical and).
            fn __rand__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::And, other, true)
            }

            /// ``self | other`` (logical or).
            fn __or__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Or, other, false)
            }

            /// ``other | self`` (logical or).
            fn __ror__(&self, py: Python<'_>, other: &Bound<'_, PyAny>) -> PyResult<Self> {
                self.apply(py, BinaryOp::Or, other, true)
            }

            /// ``~self`` (logical not).
            fn __invert__(&self, py: Python<'_>) -> PyResult<Self> {
                self.expr.not().map(|expr| Self { expr }).map_err(|error| to_py_err(py, &error))
            }

            /// Whether each value is missing (null): a boolean expression.
            ///
            /// Missing metadata is null (R9): a categorical code ``-1``, a masked
            /// nullable entry or a float ``NaN`` of an imported ``.h5ad``. A ``NaN``
            /// that kyto itself writes stays a value, not null. Matrix values and embeddings are never null (an absent
            /// sparse value is 0), so on them the result is always ``False``. Comparing
            /// with ``None`` (``x == None``) raises ``KY-E212``; use this instead.
            ///
            /// Returns
            /// -------
            /// The same expression class, of dtype ``Boolean``, never null itself.
            /// Nothing is read.
            ///
            /// Raises
            /// ------
            /// ExpressionError
            ///     ``KY-E207``: the expression would be too deep.
            fn is_null(&self, py: Python<'_>) -> PyResult<Self> {
                self.null_test(py, NullTest::IsNull)
            }

            /// Whether each value is present (not null): a boolean expression.
            ///
            /// The negation of ``is_null()``; see there for what is null (R9).
            ///
            /// Returns
            /// -------
            /// The same expression class, of dtype ``Boolean``, never null itself.
            /// Nothing is read.
            ///
            /// Raises
            /// ------
            /// ExpressionError
            ///     ``KY-E207``: the expression would be too deep.
            fn is_not_null(&self, py: Python<'_>) -> PyResult<Self> {
                self.null_test(py, NullTest::IsNotNull)
            }

            /// This column, computed again from its lineage instead of read as stored.
            ///
            /// A derived column the store computed (one whose ``schema.json`` entry
            /// records ``lineage``, such as ``n_genes``) goes stale once a step such as
            /// ``filter_genes`` changes its inputs: reading it then raises ``KY-E301``.
            /// A recomputed read is valid there. Nothing is computed now: the executor
            /// (task 5.x) computes it when the plan runs.
            ///
            /// Returns
            /// -------
            /// The same expression class and dtype. Nothing is read.
            ///
            /// Raises
            /// ------
            /// ExpressionError
            ///     ``KY-E213``: the expression is not a plain column read.
            ///
            /// Examples
            /// --------
            /// >>> cell_column("n_genes").recompute()
            /// cell_column('n_genes').recompute()
            fn recompute(&self, py: Python<'_>) -> PyResult<Self> {
                self.expr.recompute().map(|expr| Self { expr }).map_err(|error| to_py_err(py, &error))
            }

            /// Always raises ``KY-E206``: an expression has no truth value.
            fn __bool__(&self, py: Python<'_>) -> PyResult<bool> {
                Err(truth_value(py, &self.expr))
            }

            /// The dtype kind: a class from ``kyto.dtypes``.
            #[getter]
            fn dtype<'py>(&self, py: Python<'py>) -> PyResult<Bound<'py, PyAny>> {
                dtype_class(py, self.expr.dtype())
            }

            /// String functions.
            #[getter]
            fn str(&self) -> $namespace {
                $namespace { expr: self.expr.clone() }
            }

            /// The Python code that builds this expression.
            fn __repr__(&self) -> String {
                self.expr.to_string()
            }

            /// Subscripting the class, as in ``CellExpr[Numeric]``, gives a
            /// ``types.GenericAlias`` for annotations evaluated at run time.
            #[classmethod]
            fn __class_getitem__<'py>(class: &Bound<'py, PyType>, item: &Bound<'py, PyAny>) -> PyResult<Bound<'py, PyAny>> {
                class.py().import("types")?.getattr("GenericAlias")?.call1((class, item))
            }
        }

        $(#[$namespace_doc])*
        #[pyclass(frozen, module = "kyto", name = $namespace_name)]
        pub struct $namespace {
            expr: $core,
        }

        impl $namespace {
            fn call(&self, py: Python<'_>, function: StrFunction) -> PyResult<$class> {
                self.expr
                    .str(function)
                    .map(|expr| $class { expr })
                    .map_err(|error| to_py_err(py, &error))
            }
        }

        #[pymethods]
        impl $namespace {
            /// Whether each value starts with ``prefix``.
            ///
            /// Parameters
            /// ----------
            /// prefix : str
            ///     The prefix, compared byte for byte (case-sensitive).
            ///
            /// Returns
            /// -------
            /// The same expression class, of dtype ``Boolean``. Nothing is read.
            ///
            /// Raises
            /// ------
            /// ExpressionError
            ///     ``KY-E205``: the expression is not a string expression.
            fn starts_with(&self, py: Python<'_>, prefix: &str) -> PyResult<$class> {
                self.call(py, StrFunction::StartsWith(prefix.to_owned()))
            }

            /// Whether each value ends with ``suffix``.
            ///
            /// Parameters
            /// ----------
            /// suffix : str
            ///     The suffix, compared byte for byte (case-sensitive).
            ///
            /// Returns
            /// -------
            /// The same expression class, of dtype ``Boolean``. Nothing is read.
            ///
            /// Raises
            /// ------
            /// ExpressionError
            ///     ``KY-E205``: the expression is not a string expression.
            fn ends_with(&self, py: Python<'_>, suffix: &str) -> PyResult<$class> {
                self.call(py, StrFunction::EndsWith(suffix.to_owned()))
            }
        }
    };
}

