/// The `KY-E209` check of an embedding component: a non-negative `int`, not a `bool`.
fn component(constructor: &str, name: &str, value: &Bound<'_, PyAny>) -> Result<u64, KytoError> {
    let invalid = |got: String| KytoError::EmbeddingComponent {
        constructor: constructor.to_owned(),
        name: name.to_owned(),
        got,
        component: value
            .repr()
            .map_or_else(|_| "object".to_owned(), |text| text.to_string()),
    };
    if value.is_instance_of::<PyBool>() || !value.is_instance_of::<PyInt>() {
        let type_name = value
            .get_type()
            .name()
            .map_or_else(|_| "object".to_owned(), |type_name| type_name.to_string());
        let article = if type_name.starts_with(['a', 'e', 'i', 'o', 'u']) {
            "an"
        } else {
            "a"
        };
        return Err(invalid(format!("{article} {type_name}")));
    }
    value.extract::<u64>().map_err(|_| {
        invalid(
            if value.lt(0).unwrap_or(false) {
                "a negative int"
            } else {
                "an int above 2**64 - 1"
            }
            .to_owned(),
        )
    })
}

