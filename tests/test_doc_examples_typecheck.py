"""Task 7.6: every docstring example of the package type-checks with ``pyright --strict``.

The doctests prove the examples run; this proves a user copying one into a typed
project gets no type error from the stubs. Each docstring with examples (the ``.py``
modules and the ``.pyi`` stubs of ``kyto``) becomes one function of a generated file,
its ``>>>`` statements the body; an expression statement is printed, as a doctest
shows it. The file starts with the names the doctests run with (every ``kyto`` export,
and the ``store`` and ``atlas`` the method examples use). Pyright runs once, in strict
mode, on that file.
"""

import ast
import doctest
import json
import subprocess
import sys
from pathlib import Path

import kyto
import kyto.qc

_PACKAGE = Path(kyto.__file__).parent

# What the examples assume: the doctest namespaces of tests/test_docstrings.py,
# tests/test_chain.py and tests/test_atlas.py (a store path, the exports).
_PREAMBLE = f'''"""Docstring examples of kyto, generated by tests/test_doc_examples_typecheck.py."""
# pyright: strict
# pyright: reportMissingTypeStubs=false
# pyright: reportUnusedImport=false, reportUnusedVariable=false
# pyright: reportUnnecessaryIsInstance=false
from pathlib import Path

import kyto
import kyto.qc
from kyto import ({", ".join(sorted(kyto.__all__))})
from kyto.qc import ({", ".join(sorted(kyto.qc.__all__))})

store = Path("store.kyto")
store_with_members = Path("members.kyto")
'''

# Docstrings not part of the public surface: a helper module that ``Atlas.to_anndata``
# calls (anndata ships no type stubs). ``_private`` functions and methods are skipped too.
_PRIVATE_MODULES = {"_anndata.py"}

# Examples whose values come from a library without complete types: SciPy
# (``scipy-stubs`` is not in the dev env yet, a follow-up of 7.6 in the plan) and
# anndata (no stubs at all). Their ``reportUnknown*`` diagnostics are the library's, not
# kyto's stubs'.
_UNTYPED_THIRD_PARTY = {
    "_kyto.pyi.Matrix.to_scipy",
    "_kyto.pyi.Graph.to_scipy",
    "_kyto.pyi.Atlas.to_anndata",
}


def _docstrings() -> list[tuple[str, str]]:
    """(qualified name, docstring) of every module, class and function docstring."""
    found: list[tuple[str, str]] = []
    for path in sorted([*_PACKAGE.glob("*.py"), *_PACKAGE.glob("*.pyi")]):
        if path.name in _PRIVATE_MODULES:
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))

        def visit(node: ast.AST, prefix: str) -> None:
            for child in ast.iter_child_nodes(node):
                if isinstance(child, ast.ClassDef | ast.FunctionDef):
                    if child.name.startswith("_") and not child.name.endswith("__"):
                        continue
                    name = f"{prefix}.{child.name}"
                    docstring = ast.get_docstring(child)
                    if docstring:
                        found.append((name, docstring))
                    visit(child, name)

        module = path.name
        docstring = ast.get_docstring(tree)
        if docstring:
            found.append((module, docstring))
        visit(tree, module)
    return found


def _body(docstring: str) -> list[str]:
    """The example statements of a docstring, expression statements printed."""
    lines: list[str] = []
    for example in doctest.DocTestParser().get_examples(docstring):
        tree = ast.parse(example.source)
        for statement in tree.body:
            if isinstance(statement, ast.Expr):
                statement = ast.Expr(
                    ast.Call(ast.Name("print"), [statement.value], keywords=[])
                )
            lines.extend(ast.unparse(statement).splitlines())
    return lines


def examples_source() -> tuple[str, int]:
    """The generated file, and how many docstrings with examples it holds."""
    parts = [_PREAMBLE]
    count = 0
    for name, docstring in _docstrings():
        body = _body(docstring)
        if not body:
            continue
        count += 1
        function = "example_" + name.replace(".", "_")
        parts.append(f"\n\ndef {function}() -> None:  # {name}")
        parts.extend(f"    {line}" for line in body)
    return "\n".join(parts) + "\n", count


def _example_of(lines: list[str], index: int) -> str:
    """The docstring whose example holds line ``index`` of the generated file."""
    for line in reversed(lines[: index + 1]):
        if line.startswith("def example_"):
            return line.rsplit("# ", 1)[1]
    return ""


def test_doc_examples_typecheck(tmp_path: Path) -> None:
    source, count = examples_source()
    assert count > 100, "the collector found almost no examples"
    (tmp_path / "examples.py").write_text(source, encoding="utf-8")
    (tmp_path / "pyrightconfig.json").write_text(
        json.dumps({"typeCheckingMode": "strict", "pythonVersion": "3.13"}),
        encoding="utf-8",
    )
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "pyright",
            "--outputjson",
            "--pythonpath",
            sys.executable,
            "-p",
            str(tmp_path),
        ],
        cwd=tmp_path,
        check=False,  # pyright exits non-zero on errors; the report says which
        capture_output=True,
        text=True,
    )
    report = json.loads(result.stdout)
    lines = source.splitlines()
    problems = [
        f"{lines[d['range']['start']['line']]}: {d['message']}"
        for d in report["generalDiagnostics"]
        if d["severity"] == "error"
        and not (
            d.get("rule", "").startswith("reportUnknown")
            and _example_of(lines, d["range"]["start"]["line"]) in _UNTYPED_THIRD_PARTY
        )
    ]
    assert report["summary"]["filesAnalyzed"] == 1
    assert not problems, "\n".join(problems)
