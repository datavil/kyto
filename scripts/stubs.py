"""Write `python/kyto/_kyto.pyi` from the bindings, or check it is current (task 7.6).

Does: run the `stub_gen` binary of `crates/kyto-py` (what `pyo3-stub-gen` gathered
from the `#[gen_stub_*]` annotations and `submit!` blocks, docstrings taken from the
Rust doc comments), merge in the hand-written part `crates/kyto-py/stubs/expressions.pyi`
(what `pyo3-stub-gen` cannot express), apply ruff's fixes and format as the gate
does, then write it. With `--check` it writes nothing and exits non-zero when the
checked-in stub differs, so the local gate and CI fail on a stub that drifted from the
bindings.

Does not: check the stub against the built extension; `tests/test_stubs.py` does (names,
signatures, docstrings), and pyright checks the types.

Usage (from the repo root)::

    uv run python scripts/stubs.py           # regenerate after changing the bindings
    uv run python scripts/stubs.py --check   # the gate's check
"""

from __future__ import annotations

import argparse
import ast
import difflib
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STUB = ROOT / "python" / "kyto" / "_kyto.pyi"
MANUAL = ROOT / "crates" / "kyto-py" / "stubs" / "expressions.pyi"
HEADER = '''# pyright: reportMissingTypeStubs=false
# Generated by `uv run python scripts/stubs.py` (task 7.6): edit the Rust bindings
# (`#[gen_stub_*]` annotations, doc comments) or crates/kyto-py/stubs/expressions.pyi,
# never this file. The gate fails when it is not current.
"""Type stub for the compiled extension module `kyto._kyto`."""
'''


def generated() -> str:
    """The stub `pyo3-stub-gen` renders from the bindings.

    Returns
    -------
    str
        The text the `stub_gen` binary prints. A new string.

    Raises
    ------
    subprocess.CalledProcessError
        If the binary does not build or fails (its stderr is printed first).
    """
    # `cargo run` sets CARGO_MANIFEST_DIR, which pyo3-stub-gen reads. It renders default
    # values with an embedded interpreter (`infer_signature`), which finds its standard
    # library through PYTHONHOME: this interpreter's.
    # PYO3_PYTHON makes pyo3's build use this interpreter too, not the first on PATH.
    environment = {
        **os.environ,
        "PYTHONHOME": sys.base_prefix,
        "PYO3_PYTHON": sys.executable,
    }
    result = subprocess.run(
        ["cargo", "run", "--quiet", "--locked", "-p", "kyto-py", "--bin", "stub_gen"],
        cwd=ROOT,
        check=False,  # its stderr is shown first, below
        env=environment,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        result.check_returncode()
    return result.stdout


def _split(text: str) -> tuple[list[str], list[str]]:
    """Split a stub into its top-level imports and what follows the last one.

    Parameters
    ----------
    text : str
        A stub whose imports all come before its other statements (a leading
        docstring and comments aside).

    Returns
    -------
    tuple[list[str], list[str]]
        The import statements' lines, and the lines after the last import. New lists.
    """
    lines = text.splitlines()
    imports = [
        node
        for node in ast.parse(text).body
        if isinstance(node, ast.Import | ast.ImportFrom)
    ]
    import_lines = [
        line
        for node in imports
        for line in lines[node.lineno - 1 : node.end_lineno or node.lineno]
    ]
    end = max((node.end_lineno or node.lineno for node in imports), default=0)
    return import_lines, lines[end:]


def _ruff(text: str, *arguments: str) -> str:
    """Run ruff on a stub text given on stdin, and return what it prints."""
    # On stdin ruff cannot tell `kyto` is first-party (it does for the file in place).
    first_party = "lint.isort.known-first-party = ['kyto']"
    result = subprocess.run(
        [
            "ruff",
            *arguments,
            "--config",
            first_party,
            "--stdin-filename",
            str(STUB),
            "-",
        ],
        cwd=ROOT,
        input=text,
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout


def build(generated_text: str, manual_text: str) -> str:
    """Merge the generated and the hand-written stub into the file's text.

    Parameters
    ----------
    generated_text : str
        What `stub_gen` prints.
    manual_text : str
        The text of `crates/kyto-py/stubs/expressions.pyi`.

    Returns
    -------
    str
        The stub: one header, the imports of both parts (sorted by ruff), the
        generated part, then the hand-written part; fixed (`ruff check --fix`, the
        project rules) and formatted by ruff, as the gate leaves it.
    """
    generated_imports, generated_body = _split(generated_text)
    manual_imports, manual_body = _split(manual_text)
    text = "\n".join(
        [
            HEADER,
            *generated_imports,
            *manual_imports,
            "",
            *generated_body,
            "",
            "# Hand-written: crates/kyto-py/stubs/expressions.pyi",
            "",
            *manual_body,
            "",
        ]
    )
    text = _ruff(text, "check", "--fix", "--exit-zero", "--quiet")
    return _ruff(text, "format", "--quiet")


def main(argv: list[str] | None = None) -> int:
    """Write the stub, or with `--check` compare it; return the exit status."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail if python/kyto/_kyto.pyi is not current",
    )
    arguments = parser.parse_args(argv)
    text = build(generated(), MANUAL.read_text(encoding="utf-8"))
    current = STUB.read_text(encoding="utf-8") if STUB.exists() else ""
    if not arguments.check:
        if text != current:
            STUB.write_text(text, encoding="utf-8")
        print(f"wrote {STUB.relative_to(ROOT)}")
        return 0
    if text == current:
        print(f"{STUB.relative_to(ROOT)} is current")
        return 0
    diff = difflib.unified_diff(
        current.splitlines(),
        text.splitlines(),
        "checked in",
        "from the bindings",
        lineterm="",
        n=1,
    )
    print("\n".join(list(diff)[:60]), file=sys.stderr)
    print(
        f"{STUB.relative_to(ROOT)} drifted from the bindings: run "
        "`uv run python scripts/stubs.py` and commit the result",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
