"""Write `llms.txt` and `llms-full.txt` from the stubs, or check they are current (8.6).

Does: read the public surface of `kyto` from its sources, the way a type checker sees
it: the names in the `__all__` of `kyto`, `kyto.qc` and `kyto.dtypes` (each followed to
the module that defines it: `_kyto.pyi` for the extension, generated by
`scripts/stubs.py` with the docstrings of the Rust source), and the public classes of
`_kyto.pyi` with their public methods and properties. For each it writes the signature,
the summary and the `Examples` section of its NumPy docstring into `llms.txt`, and the
whole docstring into `llms-full.txt`. With `--check` it writes nothing and exits
non-zero when a checked-in file differs, so the local gate and CI fail on docs that
drifted from the stubs.

Does not: import kyto or run the examples. `tests/test_llms_txt.py` checks that every
public item of the built package has an entry with an example, and runs each example
as a doctest.

Usage (from the repo root)::

    uv run python scripts/llms_txt.py           # regenerate after changing a docstring
    uv run python scripts/llms_txt.py --check   # the gate's check
"""

from __future__ import annotations

import argparse
import ast
import difflib
import re
import sys
import textwrap
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "python" / "kyto"
LLMS = ROOT / "llms.txt"
LLMS_FULL = ROOT / "llms-full.txt"

# The namespaces whose `__all__` is public, in the order of the files' sections.
NAMESPACES = ("kyto", "kyto.qc", "kyto.dtypes")

# What an item without an example says instead (`tests/test_llms_txt.py` allows no
# other item to lack one).
NO_EXAMPLE = {
    "Modality": "store format v0 holds no modalities, so no store can build one yet",
}

INTRODUCTION = """\
kyto is a lazy, streaming single-cell analysis library written in Rust and used from
Python. Chained methods on an `Atlas` build a plan; nothing reads the matrix until a
terminal (`collect`, `sink_*`, `pull`, `select`, `to_*`) runs it.

How to use it:

- Start from a store: `kyto.convert(...)` imports 10x, `.h5ad` and Matrix Market
  data, `kyto.scan(path)` opens it as a lazy `Atlas`.
- Chain methods (`filter`, `normalize_total`, `log1p`, `highly_variable_genes`,
  `pca`, `neighbors`, `leiden`, `umap`, ...). Each returns a new plan (no mutation).
- Inspect a plan without reading data: `schema()`, `peek()`, `explain()`,
  `estimate()`, `to_json()`.
- Run it with a terminal: `collect()` or `sink_zarr(...)` / `sink_h5ad(...)`, or read
  parts as Polars, NumPy or SciPy through `pull`, `select` and the handles'
  `to_*` methods (each says whether it copies).
- Expressions are typed by axis: `cell_column`, `gene_expression`, `kyto.qc.*`
  build `CellExpr`, `gene_column` and `cell_profile` build `GeneExpr`; mixing them
  fails when the plan is built.
- Every error is a `KytoError` subclass with a stable `KY-Exxx` code and a fix.
- Seed, layer, device and memory limit are arguments; there is no global state.

The examples run as doctests (`tests/test_llms_txt.py`) in a namespace holding every
name of `kyto` and `kyto.qc`, and `store`: the path of a small `.kyto` store of 2
cells (`AAAC-1`, `AAAG-1`) by 3 genes (`CD3E`, `CD4`, `MS4A1`) with one integer
layer `counts`; `store_with_members` is a copy whose schema also lists an embedding
`X_pca` and a graph `connectivities`.
"""


@dataclass(frozen=True)
class Entry:
    """One public item: a function, a class, or a method or property of a class.

    Attributes
    ----------
    name : str
        Its qualified name as written in the files, such as `scan`, `qc.total_counts`
        or `Atlas.pca`.
    signatures : tuple of str
        One line per overload: `name(parameters) -> return`, `class Name(bases)`
        or `Name.property: type`.
    docstring : str
        The cleaned docstring (empty if it has none).
    """

    name: str
    signatures: tuple[str, ...]
    docstring: str


@dataclass(frozen=True)
class Section:
    """A heading of the files and its entries, in order."""

    title: str
    entries: tuple[Entry, ...]


_PREFIXES = re.compile(r"\b(?:builtins|typing|collections\.abc|typing_extensions)\.")


def _plain(text: str) -> str:
    """Drop the module prefixes that only qualify builtins and typing names."""
    return _PREFIXES.sub("", text)


def _module_path(module: str) -> Path:
    """The source of a `kyto` module: its `.pyi` stub for the extension, else `.py`."""
    if module == "kyto":
        return PACKAGE / "__init__.py"
    relative = Path(*module.split(".")[1:])
    if module == "kyto._kyto":
        return PACKAGE / relative.with_suffix(".pyi")
    source = PACKAGE / relative.with_suffix(".py")
    if source.exists():
        return source
    return PACKAGE / relative / "__init__.py"


def _parse(path: Path) -> ast.Module:
    return ast.parse(path.read_text(encoding="utf-8"))


def _all(tree: ast.Module) -> list[str]:
    """The names in a module's `__all__`, in its order."""
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and any(
                isinstance(target, ast.Name) and target.id == "__all__"
                for target in node.targets
            )
            and isinstance(node.value, ast.List)
        ):
            return [
                element.value
                for element in node.value.elts
                if isinstance(element, ast.Constant) and isinstance(element.value, str)
            ]
    raise ValueError("no __all__ list")


def _definition(module: str, name: str) -> tuple[str, ast.ClassDef | ast.FunctionDef]:
    """Follow `name` of `module` through its imports to where it is defined."""
    tree = _parse(_module_path(module))
    for node in tree.body:
        if isinstance(node, ast.ClassDef | ast.FunctionDef) and node.name == name:
            return module, node
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.module:
            for alias in node.names:
                if (alias.asname or alias.name) == name:
                    return _definition(node.module, alias.name)
    raise LookupError(f"{module}.{name} is not defined in the package sources")


def _is_typed_dict(node: ast.ClassDef) -> bool:
    return any(_plain(ast.unparse(base)) == "TypedDict" for base in node.bases)


def _decorators(node: ast.FunctionDef) -> set[str]:
    return {_plain(ast.unparse(decorator)) for decorator in node.decorator_list}


def _signature(node: ast.ClassDef | ast.FunctionDef, name: str) -> str:
    """`name(parameters) -> return` with `self` dropped, or `class name(bases)`."""
    if isinstance(node, ast.ClassDef):
        bases = ", ".join(_plain(ast.unparse(base)) for base in node.bases)
        return f"class {name}({bases})" if bases else f"class {name}"
    returns = _plain(ast.unparse(node.returns)) if node.returns else "None"
    if "property" in _decorators(node):
        return f"{name}: {returns}"
    return f"{name}({', '.join(_parameters(node.args))}) -> {returns}"


def _parameter(argument: ast.arg, default: ast.expr | None) -> str:
    """`name: type = default`, spaced as ruff formats a signature."""
    text = argument.arg
    if argument.annotation is not None:
        text += f": {_plain(ast.unparse(argument.annotation))}"
        if default is not None:
            text += f" = {ast.unparse(default)}"
    elif default is not None:
        text += f"={ast.unparse(default)}"
    return text


def _parameters(arguments: ast.arguments) -> list[str]:
    """The parameters of a signature, `self` or `cls` dropped, `/` and `*` kept."""
    positional = [*arguments.posonlyargs, *arguments.args]
    defaults: list[ast.expr | None] = [None] * (
        len(positional) - len(arguments.defaults)
    )
    defaults.extend(arguments.defaults)
    parts: list[str] = []
    for index, (argument, default) in enumerate(zip(positional, defaults, strict=True)):
        if index == 0 and argument.arg in {"self", "cls"}:
            continue  # a `/` right after it would have nothing before it
        parts.append(_parameter(argument, default))
        if index + 1 == len(arguments.posonlyargs):
            parts.append("/")
    if arguments.vararg is not None:
        parts.append("*" + _parameter(arguments.vararg, None))
    elif arguments.kwonlyargs:
        parts.append("*")
    for argument, default in zip(
        arguments.kwonlyargs, arguments.kw_defaults, strict=True
    ):
        parts.append(_parameter(argument, default))
    if arguments.kwarg is not None:
        parts.append("**" + _parameter(arguments.kwarg, None))
    return parts


def _functions(
    body: list[ast.stmt], prefix: str
) -> list[tuple[str, list[ast.FunctionDef]]]:
    """Public functions of a body by name, overloads grouped, in first-seen order."""
    grouped: dict[str, list[ast.FunctionDef]] = {}
    for node in body:
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            grouped.setdefault(f"{prefix}{node.name}", []).append(node)
    return list(grouped.items())


def _entry(name: str, nodes: list[ast.FunctionDef] | list[ast.ClassDef]) -> Entry:
    """The entry of one item: every overload's signature, the documented docstring."""
    docstrings = [ast.get_docstring(node) for node in nodes]
    return Entry(
        name=name,
        signatures=tuple(_signature(node, name) for node in nodes),
        docstring=next((text for text in docstrings if text), ""),
    )


def _class_entries(node: ast.ClassDef, name: str) -> list[Entry]:
    """A class and, after it, its public methods and properties."""
    entries = [_entry(name, [node])]
    for method, overloads in _functions(node.body, f"{name}."):
        entries.append(_entry(method, overloads))
    return entries


def sections() -> list[Section]:
    """The public surface, read from the sources, in the order the files list it.

    Returns
    -------
    list of Section
        New lists: the functions of `kyto`, the classes of plans, handles and
        expressions (`_kyto.pyi`), `kyto.qc`, `kyto.dtypes`, and the exceptions.

    Raises
    ------
    LookupError
        If a name of an `__all__` is defined nowhere in the package sources.
    """
    functions: list[Entry] = []
    exceptions: list[Entry] = []
    by_namespace: dict[str, list[Entry]] = {"kyto.qc": [], "kyto.dtypes": []}
    for namespace in NAMESPACES:
        prefix = "" if namespace == "kyto" else namespace.removeprefix("kyto.") + "."
        for exported in _all(_parse(_module_path(namespace))):
            module, node = _definition(namespace, exported)
            name = f"{prefix}{exported}"
            if namespace != "kyto":
                if isinstance(node, ast.ClassDef):
                    by_namespace[namespace].extend(_class_entries(node, name))
                else:
                    by_namespace[namespace].append(_entry(name, [node]))
            elif isinstance(node, ast.ClassDef) and module == "kyto.errors":
                exceptions.append(_entry(name, [node]))
            elif isinstance(node, ast.FunctionDef):
                functions.append(_entry(name, [node]))
            else:
                raise LookupError(f"kyto.{exported}: not a function or an exception")
    classes: list[Entry] = []
    for node in _parse(_module_path("kyto._kyto")).body:
        if (
            isinstance(node, ast.ClassDef)
            and not node.name.startswith("_")
            and not _is_typed_dict(node)
        ):
            classes.extend(_class_entries(node, node.name))
    return [
        Section("Functions (`kyto`)", tuple(functions)),
        Section("Plans, handles and expressions", tuple(classes)),
        Section("QC metrics (`kyto.qc`)", tuple(by_namespace["kyto.qc"])),
        Section(
            "Expression dtypes (`kyto.dtypes`)", tuple(by_namespace["kyto.dtypes"])
        ),
        Section("Errors (`kyto.errors`, also at top level)", tuple(exceptions)),
    ]


# The NumPy docstring sections; a dashed line under any other text (an example's
# output, say) is not a heading.
_SECTIONS = (
    "Parameters|Returns|Yields|Receives|Raises|Warns|Other Parameters|Attributes|"
    "Methods|See Also|Notes|References|Examples"
)
_HEADING = re.compile(rf"^({_SECTIONS})\n(-+)$", re.MULTILINE)


def docstring_sections(docstring: str) -> dict[str, str]:
    """Split a NumPy docstring into its summary and its named sections.

    Parameters
    ----------
    docstring : str
        A cleaned docstring.

    Returns
    -------
    dict of str to str
        A new dict: `""` maps to the text before the first section heading, each
        heading (`"Parameters"`, `"Examples"`, ...) to its dedented body.
    """
    found: dict[str, str] = {}
    matches = [
        match
        for match in _HEADING.finditer(docstring)
        if len(match.group(2)) == len(match.group(1).strip())
    ]
    found[""] = docstring[: matches[0].start()] if matches else docstring
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else None
        found[match.group(1).strip()] = textwrap.dedent(docstring[match.end() : end])
    return {key: value.strip("\n") for key, value in found.items()}


def _summary(docstring: str) -> str:
    """The first paragraph of the docstring's summary, as one line."""
    paragraph = docstring_sections(docstring)[""].strip().split("\n\n")[0]
    return " ".join(line.strip() for line in paragraph.splitlines())


def _render_entry(entry: Entry, *, full: bool) -> list[str]:
    lines = [f"### {entry.name}", "", "```python", *entry.signatures, "```", ""]
    if full:
        if entry.docstring:
            lines.extend([entry.docstring, ""])
        return lines
    summary = _summary(entry.docstring)
    if summary:
        lines.extend([summary, ""])
    example = docstring_sections(entry.docstring).get("Examples")
    if example:
        lines.extend(["```python", example, "```", ""])
    else:
        owner = entry.name.split(".")[0]
        reason = NO_EXAMPLE.get(owner, "none yet")
        lines.extend([f"No example: {reason}.", ""])
    return lines


def render(all_sections: list[Section], *, full: bool) -> str:
    """The text of `llms.txt` (`full=False`) or `llms-full.txt` (`full=True`).

    Parameters
    ----------
    all_sections : list of Section
        What `sections()` returns.
    full : bool
        Whole docstrings instead of summary and example.

    Returns
    -------
    str
        A new string, ending in one newline.
    """
    generated = "Generated by `uv run python scripts/llms_txt.py` (task 8.6) from"
    lines = [
        "# kyto",
        "",
        (
            "> Lazy, streaming single-cell analysis: Rust does the work, Python builds "
            "typed plans."
        ),
        "",
        (
            f"<!-- {generated} the stubs; edit the docstrings (Rust doc comments), "
            "never this file. -->"
        ),
        "",
        INTRODUCTION,
    ]
    if full:
        lines.append("Every public item with its whole NumPy docstring.\n")
    else:
        lines.append(
            "Every public item with its signature, summary and example; "
            "`llms-full.txt` has the whole docstrings (parameters, returns, "
            "raises, copies).\n"
        )
    for section in all_sections:
        lines.extend([f"## {section.title}", ""])
        for entry in section.entries:
            lines.extend(_render_entry(entry, full=full))
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write both files, or with `--check` compare them; return the exit status."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail if llms.txt or llms-full.txt is not current",
    )
    arguments = parser.parse_args(argv)
    all_sections = sections()
    status = 0
    for path, full in ((LLMS, False), (LLMS_FULL, True)):
        text = render(all_sections, full=full)
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        name = path.relative_to(ROOT)
        if not arguments.check:
            if text != current:
                path.write_text(text, encoding="utf-8")
            print(f"wrote {name}")
            continue
        if text == current:
            print(f"{name} is current")
            continue
        diff = difflib.unified_diff(
            current.splitlines(),
            text.splitlines(),
            "checked in",
            "from the stubs",
            lineterm="",
            n=1,
        )
        print("\n".join(list(diff)[:60]), file=sys.stderr)
        print(
            f"{name} drifted from the stubs: run "
            "`uv run python scripts/llms_txt.py` and commit the result",
            file=sys.stderr,
        )
        status = 1
    return status


if __name__ == "__main__":
    sys.exit(main())
