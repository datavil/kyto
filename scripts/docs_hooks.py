"""mkdocs hooks of the docs site (task 10.5): generate pages, point links at the repo.

Does: add the pages that are generated, never written by hand, to the site when it
builds (`mkdocs.yml` lists this file under `hooks`):

- `index.md`, the README;
- `design-rules.md`, R1-R12 from the canonical list in `Implementation Plan.md`;
- one `api/*.md` page per section of `llms.txt` (`scripts/llms_txt.py`'s `sections`,
  read from the generated stubs), each item a mkdocstrings `:::` block, so the API
  reference shows the NumPy docstrings and the doctested examples of the stubs.

It also rewrites relative links to files outside `docs/` (`AGENTS.md`,
`deviations.md`, a test) as links to the file on GitHub, so every link of the site
resolves and `mkdocs build --strict` passes.

Does not: write files into `docs/` (the generated pages exist only in the build), or
generate `docs/errors.md`: that page is generated by `scripts/error_registry.py` and
checked in, because every error's `docs_url` points at it on GitHub.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path
from types import ModuleType
from typing import Any
from urllib.parse import quote, unquote

import griffe
from mkdocs.config.defaults import MkDocsConfig
from mkdocs.structure.files import File, Files
from mkdocs.structure.pages import Page

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
PLAN = ROOT / "Implementation Plan.md"
README = ROOT / "README.md"

# Each llms.txt section: its page, its title, and the module path of its items.
API_PAGES = {
    "Functions (`kyto`)": ("api/functions.md", "Functions", "kyto"),
    "Plans, handles and expressions": (
        "api/classes.md",
        "Plans, handles and expressions",
        "kyto._kyto",
    ),
    "QC metrics (`kyto.qc`)": ("api/qc.md", "QC metrics", "kyto"),
    "Expression dtypes (`kyto.dtypes`)": (
        "api/dtypes.md",
        "Expression dtypes",
        "kyto",
    ),
    "Errors (`kyto.errors`, also at top level)": (
        "api/errors.md",
        "Exceptions",
        "kyto.errors",
    ),
}

# A code span (left as it is), or the target of an inline link (`](target "title")`,
# `](<target with spaces>)`) or of a reference definition (`[name]: target`).
_LINK = re.compile(
    r"(?P<code>(`+).*?(?<!`)\2(?!`))"
    r"|(?P<angle_open>\]\(\s*<)(?P<angle>[^>\n]+)"
    r"|(?P<open>\]\(\s*)(?P<inline>[^)\s]+)"
    r"|(?P<definition>^ {0,3}\[[^\]]+\]:\s*<?)(?P<reference>\S+?)(?=>|\s|$)"
)
_FENCE = re.compile(r"^(```|~~~)")


class OverloadOnlyMembers(griffe.Extension):
    """Keep stub methods that are only `@overload`s (no implementation) as members.

    griffe attaches overloads to the implementation that follows them; a `.pyi`
    method written only as overloads (`Atlas.filter`, `Atlas.resolve`,
    `Atlas.explain`) has none, so griffe would leave it out of its class and the API
    reference would not show it. The overload carrying the docstring becomes the
    member, with every overload listed. `mkdocs.yml` loads this class by path.
    """

    def on_class_members(
        self,
        *,
        node: Any,
        cls: griffe.Class,
        agent: Any,
        **kwargs: Any,
    ) -> None:
        for name, overloads in cls.overloads.items():
            if name in cls.members or not overloads:
                continue
            documented = [item for item in overloads if item.docstring is not None]
            member = documented[0] if documented else overloads[0]
            member.overloads = list(overloads)
            cls.set_member(name, member)


def _llms_txt() -> ModuleType:
    """`scripts/llms_txt.py`, imported by path (scripts/ is not a package)."""
    spec = importlib.util.spec_from_file_location(
        "kyto_llms_txt", ROOT / "scripts" / "llms_txt.py"
    )
    if spec is None or spec.loader is None:
        raise ImportError("scripts/llms_txt.py cannot be loaded")
    module = importlib.util.module_from_spec(spec)
    # dataclasses looks the module up by name while it runs.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def design_rules(plan_text: str) -> str:
    """The design-rules page: the plan's `**Design rules**` list, as written there.

    Raises
    ------
    ValueError
        If the plan has no `**Design rules**` paragraph followed by R1 to R12.
    """
    lines = plan_text.splitlines()
    try:
        start = next(
            index
            for index, line in enumerate(lines)
            if line.startswith("**Design rules**")
        )
    except StopIteration:
        raise ValueError("Implementation Plan.md: no **Design rules** list") from None
    rules: list[str] = []
    for line in lines[start + 1 :]:
        if line.startswith("- **R"):
            rules.append(line)
        elif rules and not line.strip():
            break
    numbers = [re.match(r"- \*\*R(\d+) ", rule) for rule in rules]
    if [int(match.group(1)) if match else 0 for match in numbers] != list(range(1, 13)):
        raise ValueError("Implementation Plan.md: the design rules are not R1 to R12")
    return "\n".join(
        [
            "# Design rules",
            "",
            "The rules every part of kyto follows. Reviews, commit messages and this",
            "site cite them by number (R1 to R12). They change only by a decision",
            "recorded in the implementation plan, which holds this list.",
            "",
            *rules,
            "",
        ]
    )


def api_pages() -> dict[str, str]:
    """The API reference pages by path: one per `llms.txt` section, in its order.

    Raises
    ------
    KeyError
        If `llms.txt` has a section this module does not map to a page.
    """
    pages: dict[str, str] = {}
    for section in _llms_txt().sections():
        path, title, module = API_PAGES[section.title]
        prefix = {"kyto._kyto": "", "kyto.errors": ""}.get(module)
        blocks: list[str] = []
        for entry in section.entries:
            # Methods and properties are rendered inside their class.
            depth = entry.name.count(".")
            namespaced = section.title.startswith(("QC", "Expression"))
            if depth != (1 if namespaced else 0):
                continue
            name = entry.name if prefix is None else prefix + entry.name
            blocks += [f"::: {module}.{name}", ""]
        pages[path] = "\n".join([f"# {title}", "", *blocks])
    return pages


def on_files(files: Files, config: MkDocsConfig) -> Files:
    """Add the generated pages to the build."""
    generated = {
        "index.md": README.read_text(encoding="utf-8"),
        "design-rules.md": design_rules(PLAN.read_text(encoding="utf-8")),
        **api_pages(),
    }
    for path, content in generated.items():
        files.append(File.generated(config, path, content=content))
    return files


def _source_folder(page: Page) -> Path:
    """The folder a page's relative links were written against."""
    if page.file.src_uri == "index.md":
        return ROOT
    return (DOCS / page.file.src_uri).parent


def _rewrite(target: str, folder: Path, page_folder: Path, repo_url: str) -> str:
    """One link target, made to resolve from the page in the built site."""
    if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith(("#", "/")):
        return target
    path_part, _, fragment = target.partition("#")
    path_part, _, query = path_part.partition("?")
    if not path_part:
        return target
    resolved = (folder / unquote(path_part)).resolve()
    suffix = (f"?{query}" if query else "") + (f"#{fragment}" if fragment else "")
    if resolved.is_relative_to(DOCS):
        relative = Path(
            *[".."] * len(page_folder.relative_to(DOCS).parts),
            resolved.relative_to(DOCS),
        )
        return quote(relative.as_posix()) + suffix
    if resolved.is_relative_to(ROOT) and resolved.exists():
        kind = "tree" if resolved.is_dir() else "blob"
        relative = quote(resolved.relative_to(ROOT).as_posix())
        return f"{repo_url}/{kind}/main/{relative}{suffix}"
    return target


def _replace(
    match: re.Match[str], folder: Path, page_folder: Path, repo_url: str
) -> str:
    """One `_LINK` match, its target rewritten (a code span is kept as it is)."""
    if match.group("code") is not None:
        return match.group(0)
    lead = match.group("angle_open") or match.group("open") or match.group("definition")
    target = match.group("angle") or match.group("inline") or match.group("reference")
    return lead + _rewrite(target, folder, page_folder, repo_url)


def on_page_markdown(
    markdown: str, page: Page, config: MkDocsConfig, files: Files, **_: Any
) -> str:
    """Point relative links outside `docs/` at GitHub; leave code blocks alone."""
    folder = _source_folder(page)
    page_folder = (DOCS / page.file.src_uri).parent
    repo_url = str(config.repo_url).rstrip("/")
    out: list[str] = []
    in_fence = False
    for line in markdown.splitlines(keepends=True):
        if _FENCE.match(line.lstrip()):
            in_fence = not in_fence
        if not in_fence:
            line = _LINK.sub(
                lambda match: _replace(match, folder, page_folder, repo_url), line
            )
        out.append(line)
    return "".join(out)
